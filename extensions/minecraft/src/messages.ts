function flatten(tree: Tree, prefix = '', out: Record<string, string> = {}): Record<string, string> {
  for (const [key, value] of Object.entries(tree)) {
    if (typeof value === 'string') {
      out[prefix + key] = value
      continue
    }
    flatten(value, `${prefix}${key}.`, out)
  }
  return out
}

